// Generates src/core/settings/countries.ts: ISO 3166-1 alpha-2 codes with their names in en, es and fr, from the
// ICU data of the Node running this script. Run: npm run gen:countries
import { writeFileSync } from 'node:fs';

const names = Object.fromEntries(
  ['en', 'es', 'fr'].map((locale) => [locale, new Intl.DisplayNames([locale], { type: 'region' })]),
);
const rows = [];
for (let a = 65; a <= 90; a++) {
  for (let b = 65; b <= 90; b++) {
    const code = String.fromCharCode(a, b);
    let en;
    try {
      en = names.en.of(code);
    } catch {
      continue;
    }
    // Unassigned codes come back as the code itself.
    if (!en || en === code) continue;
    // Skip the user-assigned and reserved codes ICU still names, and the pseudo-regions.
    if (['AC', 'CP', 'DG', 'EA', 'EU', 'EZ', 'IC', 'TA', 'UN', 'XA', 'XB', 'XK', 'ZZ', 'QO'].includes(code)) continue;
    rows.push([code, en, names.es.of(code), names.fr.of(code)]);
  }
}
const body = rows.map(([c, en, es, fr]) => `  ${JSON.stringify(c)}: ${JSON.stringify({ en, es, fr })},`).join('\n');
writeFileSync(
  new URL('../src/core/settings/countries.ts', import.meta.url),
  `// Generated by scripts/gen-countries.mjs. Do not edit.\nexport const COUNTRY_NAMES: Readonly<Record<string, { en: string; es: string; fr: string }>> = {\n${body}\n};\n`,
);
console.log(`${rows.length} countries`);
