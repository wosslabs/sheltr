// Generates src/platform/sampleBundleAssets.ts: static require()s for every file of the sample bundle, because
// Metro can only bundle files it can see at build time. Run after replacing assets/sample-bundle:
//   npm run gen:sample
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../assets/sample-bundle/', import.meta.url);
const manifest = JSON.parse(readFileSync(new URL('bundle.json', root), 'utf8'));
const files = new Set(readdirSync(new URL('documents/', root)));

const lines = manifest.documents.map((d) => {
  if (!files.has(`${d.id}.json`)) throw new Error(`documents/${d.id}.json is listed in bundle.json but missing`);
  return `  ${JSON.stringify(d.id)}: require('../../assets/sample-bundle/documents/${d.id}.json') as unknown,`;
});
writeFileSync(
  new URL('../src/platform/sampleBundleAssets.ts', import.meta.url),
  `// Generated by scripts/gen-sample-index.mjs. Do not edit.
/* eslint-disable @typescript-eslint/no-require-imports */
export const SAMPLE_MANIFEST = require('../../assets/sample-bundle/bundle.json') as unknown;

export const SAMPLE_DOCUMENTS: Readonly<Record<string, unknown>> = {
${lines.join('\n')}
};
`,
);
console.log(`${manifest.documents.length} documents`);
