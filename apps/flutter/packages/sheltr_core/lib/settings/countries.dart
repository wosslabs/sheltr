/// Display names for the country picker.
class CountryNames {
  const CountryNames({required this.en, required this.es, required this.fr});

  final String en;
  final String es;
  final String fr;

  /// [languageCode] is `en`, `es`, or `fr`. Anything else uses English.
  String forLanguage(String languageCode) {
    switch (languageCode) {
      case 'es':
        return es;
      case 'fr':
        return fr;
      default:
        return en;
    }
  }
}

